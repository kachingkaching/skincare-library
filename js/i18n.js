/* Interface language.

   Three languages, one flat dictionary each, keyed by dotted names. `t()` is
   synchronous and never throws: an untranslated key falls back to English and
   an unknown key returns itself, so a missing string shows up in the interface
   as a visible key rather than as a blank space or a crash.

   The chosen language is read from IndexedDB once at boot, before the first
   render, and held in a module variable — every view calls `t()` while building
   its markup, and none of them can await.

   INCI names are deliberately left as printed. They appear in Latin on the pack
   in every market, and matching what you are holding against what is on screen
   matters more than reading it in your own language. Everything *about* an
   ingredient — what it does, and its tags — is translated. */

import { ING_HANT, ING_HANS } from './ingredients.i18n.js';

/* This module imports nothing but data, on purpose. Everything else in the app
   needs `t()`, including store.js and rules.js, so anything it imported back
   would close a cycle — which ES modules tolerate and the flattened share build
   does not. Reading and writing the stored preference is therefore the caller's
   job; see `applyLang` and app.js. */

export const LANGS = [
  { id: 'en',      label: 'English',  short: 'EN' },
  { id: 'zh-Hant', label: '繁體中文', short: '繁' },
  { id: 'zh-Hans', label: '简体中文', short: '简' }
];

let current = 'en';

export const lang = () => current;

/* What the model is told to write in. */
export const LANG_NAME = {
  en: 'English',
  'zh-Hant': 'Traditional Chinese (繁體中文), as written in Hong Kong and Taiwan',
  'zh-Hans': 'Simplified Chinese (简体中文)'
};

/* A stored choice wins; failing that, take the browser's own preference, so a
   Chinese-language browser opens in Chinese without being asked. */
export function chooseLang(stored) {
  if (stored && LANGS.some(l => l.id === stored)) return stored;
  const tags = navigator.languages || [navigator.language || 'en'];
  const zh = tags.find(x => /^zh/i.test(x));
  if (zh) return /hant|tw|hk|mo/i.test(zh) ? 'zh-Hant' : 'zh-Hans';
  return 'en';
}

export function applyLang(id) {
  current = LANGS.some(l => l.id === id) ? id : 'en';
  document.documentElement.lang = current;
  return current;
}

/* t('key') or t('key', { n: 3 }) — {n} in the string is replaced. */
export function t(key, vars) {
  const table = DICT[current] || DICT.en;
  let s = table[key];
  if (s === undefined) s = DICT.en[key];
  if (s === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  }
  return s;
}

/* English pluralises, Chinese does not. */
export const plural = (n, one, many) =>
  (current === 'en' ? t(n === 1 ? one : many, { n }) : t(many, { n }));

/* Chinese separates a list with an ideographic comma, not a Latin one. */
export const listSep = () => (current === 'en' ? ', ' : '、');

/* Labels that live as data elsewhere — the English in rules.js and
   ingredients.js stays the source, and these translate it on the way out.
   An unknown value falls through to itself rather than showing a raw key. */
const viaKey = (prefix, value) => {
  const key = prefix + value;
  const s = t(key);
  return s === key ? value : s;
};

export const tagLabel = tag => viaKey('tag.', tag);
export const statusLabel = status => viaKey('status.', status);
export const severityLabel = sev => viaKey('sev.', sev);
export const categoryLabel = cat => viaKey('cat.', cat);
export const stepLabel = step => viaKey('step.', step.key ?? step);
export const concernLabel = concern => viaKey('concern.', concern.key ?? concern);
export const dayLabel = day => viaKey('day.', day);

/* The sentence explaining an ingredient. The INCI name is left as printed. */
export function ingredientText(entry) {
  if (!entry) return '';
  const table = current === 'zh-Hant' ? ING_HANT : current === 'zh-Hans' ? ING_HANS : null;
  return (table && table[entry.k]) || entry.f;
}

