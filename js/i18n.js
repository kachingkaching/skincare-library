const DICT = { en, 'zh-Hant': zhHant, 'zh-Hans': zhHans };

/* Keys present in English but missing elsewhere fall back silently, which is
   the right behaviour in front of a user and the wrong one for whoever is
   maintaining the tables. Exposed so it can be checked from the console. */
export function missingKeys() {
  const out = {};
  for (const [id, table] of Object.entries(DICT)) {
    if (id === 'en') continue;
    out[id] = Object.keys(en).filter(k => !(k in table));
  }
  return out;
}
